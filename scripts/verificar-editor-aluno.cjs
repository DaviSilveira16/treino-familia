// Chamado pelo verificador SQL com PostgreSQL e RLS reais, isolados.
const assert = require("node:assert/strict");
module.exports = async ({ db, account, coach, student, stranger, link, id }) => {
  const rpc = async (action, data = {}) => (await db.query("select tf_coaching_workouts($1,$2,$3::jsonb) as result", [link.id, action, JSON.stringify(data)])).rows[0].result;
  await account(null, "anon"); await assert.rejects(rpc("list"), /permission denied/);
  await account(stranger); await assert.rejects(rpc("list"), /vínculo não está ativo/);
  await account(coach);
  await assert.rejects(db.query("select * from coaching_workout_edits"), /permission denied/);
  await assert.rejects(db.query("select tf_coaching_plan_snapshot($1,$2)", [id(999), student]), /permission denied/);
  const creation = { operation_id: id(500), name: "Edição direta" };
  let result = await rpc("create_plan", creation);
  assert.deepEqual(await rpc("create_plan", creation), result, "reenvio de criação não duplica treino");
  await assert.rejects(rpc("create_plan", { ...creation, name: "Colisão" }), /outra operação/);
  const plan = result.plan_id;
  let seq = 501;
  const change = async (action, data = {}) => {
    result = await rpc(action, { plan_id: plan, version: result.snapshot.version, operation_id: id(seq++), ...data });
    return result;
  };
  await change("create_exercise", { name: "Agachamento", sets_goal: 3, reps_goal: "8-12" });
  const exercise = result.snapshot.exercises[0].id;
  await change("create_exercise", { name: "Remada", sets_goal: 2, reps_goal: "10" });
  const second = result.snapshot.exercises[1].id;
  const stale = result.snapshot.version;
  await change("update_exercise", { exercise_id: exercise, name: "Agachamento livre", sets_goal: 4, reps_goal: "6-8" });
  assert.equal(result.snapshot.exercises[0].id, exercise, "editar mantém o identificador");
  await assert.rejects(rpc("rename_plan", { plan_id: plan, version: stale, operation_id: id(seq++), name: "Conflito" }), /mudou/);
  await change("save_loads", { exercise_id: exercise, loads: [{ reps: 8, weight_kg: 25 }, { reps: 6, weight_kg: 30 }] });
  assert.deepEqual(result.snapshot.exercises[0].loads.map(c => c.weight_kg), [25, 30]);
  const valid = result.snapshot;
  await assert.rejects(change("save_loads", { exercise_id: exercise, loads: [{ reps: 8, weight_kg: -1 }] }), /Confira/);
  assert.deepEqual(await rpc("read", { plan_id: plan }), valid, "erro não apaga referências");
  await change("move_exercise", { exercise_id: exercise, other_id: second });
  assert.equal(result.snapshot.exercises[0].id, second);
  await account(student);
  assert.equal((await db.query("select user_id from workout_plans where id=$1", [plan])).rows[0].user_id, student);
  await db.query("insert into workout_sessions(id,user_id,plan_id,started_at,status) values($1,$2,$3,now()-interval '5 days','em_andamento')", [id(600), student, plan]);
  await db.query("insert into workout_sets(id,user_id,session_id,exercise_id,exercise_name,set_number,reps,weight_kg) values($1,$2,$3,$4,'Agachamento',1,10,15)", [id(601),student,id(600),exercise]);
  await account(coach);
  await assert.rejects(change("rename_plan", { name: "Durante sessão" }), /em andamento/);
  await account(student); await db.query("update workout_sessions set status='concluido',finished_at=now()-interval '5 days' where id=$1",[id(600)]);
  await account(coach);
  await change("rename_plan", { name: "Treino ajustado" });
  const photo = `${student}/${exercise}/123.png`;
  await db.query("insert into storage.objects(bucket_id,name) values('exercise-photos',$1)",[photo]);
  await change("set_photo", { exercise_id: exercise, photo_path: photo });
  await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('profile-photos',$1)",[photo]), /row-level security/);
  await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('exercise-photos',$1)",[`${stranger}/${exercise}/123.png`]), /row-level security/);
  assert.equal((await db.query("delete from storage.objects returning id")).rows.length,0,"treinador não apaga fotos");
  await account(stranger); assert.equal((await db.query("select * from storage.objects")).rows.length,0);
  await assert.rejects(rpc("read", { plan_id: plan }), /vínculo não está ativo/);
  await account(coach);
  await change("delete_exercise", { exercise_id: exercise });
  await change("delete_plan");
  await account(student);
  const historical = (await db.query("select * from workout_sets where id=$1",[id(601)])).rows[0];
  assert.equal(historical.exercise_id,null); assert.equal(historical.exercise_name,"Agachamento"); assert.equal(Number(historical.weight_kg),15);
  assert.equal((await db.query("select plan_id from workout_sessions where id=$1",[id(600)])).rows[0].plan_id,null);
  await account(null,"postgres");
  assert.ok((await db.query("select before_snapshot from coaching_workout_edits where action='delete_plan'")).rows[0].before_snapshot);
  console.log("Editor SQL aprovado: propriedade, RLS, reenvio, conflitos, sessão ativa, fotos, edição, ordem e exclusão com histórico preservado.");
};
