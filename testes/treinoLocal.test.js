const assert = require("node:assert/strict");
const { carregar, armazenamento } = require("./suporte.cjs");
const storage = armazenamento();
const local = carregar("servicos/treinoLocal.ts", { "@react-native-async-storage/async-storage": storage });
const serie = { chave: "e1:1", exercise_id: "e1", exercise_name: "Exercício", set_number: 1, reps: "8", weight_kg: "20", concluida: false };
const draft = { versao: 1, usuarioId: "u1", planId: "p1", planName: "Plano", sessao: { id: "s1", plan_id: "p1", started_at: "2026-10-24T12:00:00Z" }, exercicios: [], series: [serie], intensidade: "moderada", esforco: "adequado", salvoEm: "2026-10-24T12:00:00Z", descanso: { fimEm: 11000, pausado: false, segundosPausados: 0, duracao: 10 } };
(async () => {
  assert.equal(local.segundosDeDescanso(draft.descanso, 1000), 10);
  assert.equal(local.segundosDeDescanso(draft.descanso, 12000), 0);
  assert.equal(local.segundosDeDescanso({ ...draft.descanso, pausado: true, segundosPausados: 7 }, 99999), 7);
  const original = [serie, { ...serie, chave: "e1:2", set_number: 2, concluida: true }, { ...serie, chave: "e1:3", set_number: 3, pendente: "salvar" }];
  const anterior = [1, 2, 3].map(set_number => ({ exercise_id: "e1", set_number, reps: 12, weight_kg: 30 }));
  const copiado = local.copiarSeriesAnteriores(original, anterior, "e1");
  assert.equal(copiado[0].reps, "12"); assert.equal(serie.reps, "8");
  assert.equal(copiado[1], original[1]); assert.equal(copiado[2], original[2]);
  assert.equal(local.copiarSeriesAnteriores([serie], [{ ...anterior[0], weight_kg: Infinity }], "e1")[0], serie);
  let notificacoes = 0; const cancelar = local.assinarRascunhos(() => notificacoes++);
  await local.gravarRascunho(draft);
  assert.equal(await local.lerResumoTreinoAtivo("u2"), null);
  const restaurado = await local.lerRascunho("u1", "p1");
  assert.equal(restaurado.descanso.fimEm, 11000);
  const originalOp = { ...serie, pendente: "salvar", registroId: "r1" };
  await local.gravarRascunho({ ...draft, series: [originalOp] });
  await local.atualizarRascunho("u1", "p1", atual => ({ ...atual, series: [{ ...atual.series[0], reps: "11" }] }));
  await local.atualizarRascunho("u1", "p1", atual => ({ ...atual, series: atual.series.map(item => local.mesmaOperacao(item, originalOp) ? { ...item, pendente: undefined } : item) }));
  assert.equal((await local.lerRascunho("u1", "p1")).series[0].pendente, "salvar", "Confirmação antiga não pode apagar edição nova");
  assert.equal((await local.lerResumoTreinoAtivo("u1")).pendencias, 1);
  await local.apagarRascunho("u1", "p1"); assert.equal(await local.lerResumoTreinoAtivo("u1"), null);
  cancelar(); assert.ok(notificacoes >= 4);
  console.log("OK — descanso persistente, cópia segura, isolamento e confirmação concorrente");
})().catch(error => { console.error(error); process.exitCode = 1; });
